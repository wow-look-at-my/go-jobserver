CREATE TABLE IF NOT EXISTS tasks (
	n        INTEGER PRIMARY KEY,
	id       TEXT NOT NULL UNIQUE,
	inbox    TEXT NOT NULL,
	state    TEXT NOT NULL,
	created  INTEGER NOT NULL,
	ended    INTEGER,
	seq      INTEGER NOT NULL,
	data     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS tasks_open ON tasks(n) WHERE ended IS NULL;
CREATE INDEX IF NOT EXISTS tasks_inbox_ended ON tasks(inbox, ended, id);
CREATE INDEX IF NOT EXISTS tasks_inbox_seq ON tasks(inbox, seq);
CREATE INDEX IF NOT EXISTS tasks_state ON tasks(state);
CREATE TABLE IF NOT EXISTS task_specs (id TEXT PRIMARY KEY, spec BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS task_results (id TEXT PRIMARY KEY, result BLOB NOT NULL);
CREATE TABLE IF NOT EXISTS task_steps (id TEXT NOT NULL, step INTEGER NOT NULL, data TEXT NOT NULL, PRIMARY KEY (id, step)) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS task_waits (id TEXT NOT NULL, wait INTEGER NOT NULL, data TEXT NOT NULL, PRIMARY KEY (id, wait)) WITHOUT ROWID;
CREATE TABLE IF NOT EXISTS cache (identity TEXT PRIMARY KEY, id TEXT NOT NULL, at INTEGER NOT NULL, data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS cache_at ON cache(at, identity);
CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
